function hexToBytes(h) {
  const clean = h.replace(/^0[xX]/, '').replace(/\s+/g, '');
  if (clean.length === 0 || clean.length % 2 !== 0) throw new Error('hex must have an even number of hex digits (got ' + clean.length + ')');
  if (!/^[0-9a-fA-F]+$/.test(clean)) throw new Error('hex contains non-hex characters');
  const out = new Uint8Array(clean.length >> 1);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(clean.substr(i * 2, 2), 16);
  return out;
}

const MAX_TEXT = 16384;   // chars
const MAX_HEX = 32768;    // hex chars (16 KB of bytes)

async function readParams(request, url) {
  const p = { text: url.searchParams.get('text'), hex: url.searchParams.get('hex') };
  if (request.method === 'POST') {
    const ct = request.headers.get('Content-Type') || '';
    if (ct.includes('application/json')) {
      try {
        const body = await request.json();
        if (body && typeof body === 'object' && !Array.isArray(body)) {
          if (typeof body.text === 'string') p.text = p.text ?? body.text;
          if (typeof body.hex === 'string') p.hex = p.hex ?? body.hex;
        }
      } catch (e) { throw new Error('request body is not valid JSON'); }
    }
  }
  return p;
}

async function handleApi(request) {
  const url = new URL(request.url);
  let p;
  try {
    p = await readParams(request, url);
  } catch (e) {
    return Response.json({ error: e.message }, { status: 400, headers: JSON_HEADERS });
  }
  if (p.text != null && p.hex != null) return Response.json({ error: 'Pass only one of text or hex, not both' }, { status: 400, headers: JSON_HEADERS });
  let bytes, inputMode, echo;
  try {
    if (p.text != null) {
      if (p.text.length > MAX_TEXT) return Response.json({ error: `text too long (max ${MAX_TEXT} chars)` }, { status: 413, headers: JSON_HEADERS });
      bytes = new TextEncoder().encode(p.text);
      inputMode = 'text'; echo = p.text;
    } else if (p.hex != null) {
      if (p.hex.length > MAX_HEX) return Response.json({ error: `hex too long (max ${MAX_HEX} hex chars = 16 KB)` }, { status: 413, headers: JSON_HEADERS });
      bytes = hexToBytes(p.hex);
      inputMode = 'hex'; echo = p.hex.length > 200 ? p.hex.slice(0, 200) + '…' : p.hex;
    } else {
      return Response.json({ error: 'Missing required parameter: text (UTF-8) or hex (raw bytes, optional 0x prefix)' }, { status: 400, headers: JSON_HEADERS });
    }
  } catch (e) {
    return Response.json({ error: 'Invalid hex input: ' + e.message }, { status: 400, headers: JSON_HEADERS });
  }
  const hash = keccak256Hex(bytes);
  return Response.json({
    input_mode: inputMode,
    input: echo,
    input_bytes: bytes.length,
    keccak256: hash,
    keccak256_0x: '0x' + hash,
    note: 'Original Keccak padding (Ethereum) — not identical to SHA3-256',
    decoded_by: 'Formatho edge API — zero tracking',
    full_tool: FULL_TOOL,
  }, { headers: JSON_HEADERS });
}

